#!/usr/bin/env bash
# Purpose: run all nine experiments in order, parse each to CSV, and leave
# Ex_notes.md with a fresh note per experiment. `--quick` reduces repeats
# for a fast end-to-end smoke test (make bench-quick); full run is `make bench`.
# Author: [GROUP MEMBER PLACEHOLDER]
# Date: [DATE PLACEHOLDER]
set -euo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

QUICK_FLAG=""
for a in "$@"; do [[ "$a" == "--quick" ]] && QUICK_FLAG="--quick"; done

mkdir -p evidence/processed
: > evidence/processed/Ex_notes.md
echo "# Experiment notes (generated by experiments/run_all.sh)" >> evidence/processed/Ex_notes.md
echo "" >> evidence/processed/Ex_notes.md

VENV_PY=".venv/bin/python3"
[[ -x "$VENV_PY" ]] || VENV_PY="python3"

run_one() {
  local id="$1"
  echo ""
  echo "=================================================================="
  echo "Running $id"
  echo "=================================================================="
  bash "experiments/run_${id}.sh" $QUICK_FLAG
  "$VENV_PY" "experiments/parse_${id}.py"
}

run_one E1
run_one E2
run_one E3
# E4's "before" nmap evidence comes from harden.sh; this captures "after".
run_one E4

bash lab/scripts/setup_e5_demo_accounts.sh
run_one E5
bash lab/scripts/teardown_e5_demo_accounts.sh

run_one E6
run_one E7
run_one E8
run_one E9

echo ""
echo "All experiments complete. CSVs in evidence/processed/, notes in evidence/processed/Ex_notes.md"
